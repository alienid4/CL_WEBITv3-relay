// ===== 以下是純函式，給頁面與測試用 =====

export const PENDING_MARK = '（待確認'

/** 一節內所有會被顯示的文字（含圖說與常見問題），用來掃描待確認與禁用字樣。 */
export function sectionTexts(s: ManualSection): string[] {
  return [s.title, s.when, ...s.steps, s.sees, ...s.notes, ...s.figures.map(f => f.caption), ...(s.links ?? []).flatMap(l => [l.label, l.tag]), ...(s.faq ?? []).flatMap(x => [x.q, x.a])]
}

/** 結構檢查：回傳問題清單，空陣列＝合格。 */
export function validateSections(list: ManualSection[]): string[] {
  const bad: string[] = []
  const seen = new Set<string>()
  list.forEach((s, i) => {
    const at = `第 ${i + 1} 節（${s.id || '無 id'}）`
    if (!s.id) bad.push(`${at}缺 id`)
    if (seen.has(s.id)) bad.push(`${at} id 重複`)
    seen.add(s.id)
    if (s.no !== i + 1) bad.push(`${at}編號應為 ${i + 1}，實際 ${s.no}`)
    if (!s.title?.trim()) bad.push(`${at}缺標題`)
    if (!s.when?.trim()) bad.push(`${at}缺「什麼時候用」`)
    if (!s.steps?.length || s.steps.some(x => !x.trim())) bad.push(`${at}缺「怎麼做」步驟`)
    if (!s.sees?.trim()) bad.push(`${at}缺「會看到什麼」`)
    if (!s.notes?.length || s.notes.some(x => !x.trim())) bad.push(`${at}缺「注意事項」`)
    for (const f of s.figures ?? []) {
      if (!f.id || !f.caption?.trim()) bad.push(`${at}有圖缺 id 或圖說`)
      if (!f.svg && !f.src) bad.push(`${at}圖 ${f.id} 沒有 svg 也沒有 src`)
    }
  })
  return bad
}

/** 把所有「（待確認…）」的句子列出來（節編號＋原句），回報用。 */
export function pendingItems(list: ManualSection[]): { no: number; text: string }[] {
  const out: { no: number; text: string }[] = []
  for (const s of list) for (const t of sectionTexts(s)) if (t.includes(PENDING_MARK)) out.push({ no: s.no, text: t })
  return out
}

/** 目錄用：依 id 找節，找不到回第一節。 */
export function pickSection(list: ManualSection[], id: string | undefined | null): ManualSection {
  return list.find(s => s.id === id) ?? list[0]
}

/** 手冊版本落後系統版本嗎（以三段數字比大小）。任一邊讀不到就當作不知道（回 false）。 */
export function manualBehind(manual: string, system: string): boolean {
  const p = (v: string) => v.split('.').map(n => Number(n))
  const a = p(manual)
  const b = p(system)
  if (a.length !== 3 || b.length !== 3 || [...a, ...b].some(n => Number.isNaN(n))) return false
  for (let i = 0; i < 3; i++) { if (a[i] !== b[i]) return a[i] < b[i] }
  return false
}
